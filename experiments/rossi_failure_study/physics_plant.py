"""Physics-based sliding-scan plant for judging separation methods on the normal axis.

The old benchmark prescribes tissue motion as a smoothstep, a cubic in time, which favours a cubic
drift model. Here motion comes out of body dynamics, so no method's model is built into the truth:

  m z'' + c (z'-u') + k (z-u) = f_ext(t) - F          body on its support, reacted by the contact force
  d = y_tool + z + h(x),  y_tool = y_enc + r(t) - F/k_r   series robot compliance, unmeasured tool ripple
  F = (f_e(x,d)(1+beta a) + sum q_i)(1 + lam d')       finite-footprint elastic force, Prony memory, damping
  q_i' = alpha_i f_e' - q_i/tau_i

Drives u, f_ext, a, r are generated by scenes.py. Truth columns are for scoring only.
Log columns: 0 t, 1 x, 2 y_enc, 3 F_true, 4 z_body, 5 F_measured, 6 d, 7 E_under, 8 k at the probe frequency,
9 k at 1 Hz, 10 instantaneous k, 11 command, 12 Ft (unused, 0), 13 My (unused, 0), 14 u, 15 activation.
"""
import math
import os
import sys
import numpy as np
from numba import njit

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'cobot_scan_benchmark'))
import plant as OLD   # geometry only: psi/halfwidth of the cylindrical footprint, Obs, platform table

R, L, X0, FD = OLD.R, OLD.L, OLD.X0, OLD.FD
NQ = OLD.NQ
halfwidth = OLD.halfwidth
PLATFORM = dict(OLD.PLATFORMS['PC125'])
LOGC = 16
NS = 16


@njit(cache=True)
def _lookup(g, dx, xi):
    u = xi/dx
    i = int(u)
    if i < 0:
        return g[0]
    if i >= len(g)-1:
        return g[-1]
    f = u-i
    return g[i]*(1-f)+g[i+1]*f


@njit(cache=True)
def _fe(xc, d, ln_e, dx, law=0.):
    """Elastic force. law = 0: finite footprint; law = p > 0: uniform power law pi L E d_r^(1-p) d^p / 4, with p = 1 the AuSoScan cylinder."""
    if d <= 0:
        return 0.
    if law > 0:
        return math.pi*L/4*math.exp(_lookup(ln_e, dx, xc-X0))*.01**(1.-law)*d**law
    a = halfwidth(d); out = 0.
    for i in range(1, NQ+1):
        th = i*math.pi/(NQ+1)
        xi = a*math.cos(th)
        w = math.pi/(NQ+1)*math.sin(th)**2*a*a
        out += L/(2*R)*math.exp(_lookup(ln_e, dx, xc+xi-X0))*w
    return out


@njit(cache=True)
def _tick(s, buf, cmd, c, ln_e, h_s, dx, u, fext, act, rip, alpha, tau, sig, noise, kk, log, nlog, direct_log):
    """Advance one 8 ms control period at 2 kHz."""
    m, cb, kb, kr, lam, beta, v_scan, tau_a, afc, ns, ndel_f, r_c, r_low, r_inst, vmax, law = c
    dt = 5e-4; ndel = int(ndel_f); Tc = .008
    ei = np.exp(-dt/tau); gi = np.exp(-dt/(2*tau))
    prev = buf[ndel]
    for q in range(ndel):
        buf[q] = buf[q+1]
    buf[ndel] = min(max(cmd, prev-vmax*Tc), prev+vmax*Tc)
    n_drive = len(u)
    kt_guess = s[15]
    for j in range(16):
        t = s[0]; it = int(t*1000+1e-9)
        i0 = min(it, n_drive-2); fr = t*1000-i0
        uu = u[i0]*(1-fr)+u[i0+1]*fr; ud = (u[i0+1]-u[i0])*1000.
        fx = fext[i0]; aa = act[i0]; rp = rip[i0]
        xc = X0+v_scan*max(t-ndel*Tc, 0.)
        s[1] += dt/tau_a*(xc-s[1])
        # body
        s[4] += dt/m*(kb*(uu-s[3])+cb*(ud-s[4])+fx-s[12]); s[3] += dt*s[4]
        h = _lookup(h_s, dx, s[1]-X0)
        base = s[2]+rp+s[3]+h
        d = s[8]; F = 0.; fe = 0.
        mod = 1.+beta*aa
        if base > 0:
            d = max(d, 1e-9)
            for _ in range(3):
                fe = _fe(s[1], d, ln_e, dx, law)*mod
                qs = 0.
                for i in range(3):
                    qs += s[9+i]*ei[i]+alpha[i]*(fe-s[7])*gi[i]
                dd = (d-s[8])/dt
                F = max((fe+qs)*(1.+lam*dd), 0.)
                res = d-(base-F/kr)
                slope = 1.+(kt_guess+lam/dt*max(F, 0.))/kr
                d = max(d-res/slope, 1e-9)
            fe = _fe(s[1], d, ln_e, dx, law)*mod
            for i in range(3):
                s[9+i] = s[9+i]*ei[i]+alpha[i]*(fe-s[7])*gi[i]
            dd = (d-s[8])/dt
            F = max((fe+s[9]+s[10]+s[11])*(1.+lam*dd), 0.)
        else:
            d = base-F/kr; fe = 0.
            s[9] = s[10] = s[11] = 0.
        s[7] = fe; s[8] = d; s[12] = F
        if abs(t*1000-round(t*1000)) < 1e-6:
            k_n = min(kk, noise.shape[0]-1)
            s[6] += 2e-4*ns*noise[k_n, 0]
            s[5] += afc*(F+s[6]+sig*ns*noise[k_n, 1]-s[5])
            kk += 1
        if j == 0 and nlog < log.shape[0]:
            if base > 0:
                hd = 2e-6
                ke = (_fe(s[1], d+hd, ln_e, dx, law)-_fe(s[1], max(d-hd, 1e-9), ln_e, dx, law))/(2*hd)*mod
            else:
                ke = 0.
            s[15] = ke*r_inst if ke > 0 else s[15]
            kc = ke*r_c; kl = ke*r_low; ki = ke*r_inst
            log[nlog, 0] = t; log[nlog, 1] = s[1]; log[nlog, 2] = s[2]; log[nlog, 3] = F; log[nlog, 4] = s[3]
            log[nlog, 5] = s[5]; log[nlog, 6] = d; log[nlog, 7] = math.exp(_lookup(ln_e, dx, s[1]-X0))*mod
            log[nlog, 8] = kc*kr/(kc+kr) if kc > 0 else 0.
            log[nlog, 9] = kl*kr/(kl+kr) if kl > 0 else 0.
            log[nlog, 10] = ki*kr/(ki+kr) if ki > 0 else 0.
            log[nlog, 11] = buf[ndel]; log[nlog, 14] = uu; log[nlog, 15] = aa
            nlog += 1
        s[2] += dt/tau_a*(buf[0]-s[2])
        s[0] = t+dt
        if not math.isfinite(s[2]) or abs(s[2]) > .5 or F > 5e3:
            return -nlog, kk
    return nlog, kk


def _constants(sc, pl):
    alpha, tau = sc['alpha'], sc['tau']
    def ratio(w):
        return 1.+float(np.sum(alpha*(w*tau)**2/(1+(w*tau)**2)))
    afc = 1.-math.exp(-2*math.pi*pl['fc']*1e-3)
    return np.array([sc['m'], sc['c'], sc['k'], sc['kr'], sc['lam'], sc['beta'], sc['v'], pl['tau_a'], afc, sc.get('noise_scale', 1.),
                     float(pl['ndel']), ratio(2*math.pi*20.8), ratio(2*math.pi), 1.+float(np.sum(alpha)), pl['VMAX'], float(sc.get('law', 0.))])


def _init(sc, pl):
    # Equilibrium at the target force with the body at rest, viscoelastic branches relaxed.
    lo, hi = 1e-7, .03
    x0 = 0.
    for _ in range(60):
        mid = .5*(lo+hi)
        if _fe(X0, mid, sc['ln_e'], sc['dx'], float(sc.get('law', 0.))) > FD:
            hi = mid
        else:
            lo = mid
    d0 = .5*(lo+hi)
    z0 = sc['u'][0]-FD/sc['k']
    y0 = d0-z0-_lookup(sc['h_s'], sc['dx'], 0.)+FD/sc['kr']
    s = np.zeros(NS)
    s[1] = X0; s[2] = y0; s[3] = z0; s[5] = FD; s[7] = FD; s[8] = d0; s[12] = FD; s[15] = 1e4
    buf = np.full(int(pl['ndel'])+1, y0)
    return s, buf


def _arrays(sc):
    return sc['ln_e'], sc['h_s'], sc['dx'], sc['u'], sc['fext'], sc['act'], sc['rip'], sc['alpha'], sc['tau']


def episode(sc, policy, seed, platform=None, sensor=True):
    """Closed-loop run. policy(Obs) returns an absolute position command, as the old direct mode."""
    pl = dict(PLATFORM if platform is None else platform)
    T = sc['T']; nt = int(round(T/pl['Tc']))
    log = np.zeros((nt+2, LOGC)); s, buf = _init(sc, pl)
    c = _constants(sc, pl)
    rng = np.random.default_rng(seed)
    noise = rng.standard_normal((int(T*1000)+10, 2)) if sensor else np.zeros((int(T*1000)+10, 2))
    sig = .08; kk = 0
    policy.reset(pl)
    a = _arrays(sc)
    n = 0
    while n < nt:
        x_, y_ = s[1], s[2]
        log[n, :] = 0.; log[n, 0] = s[0]; log[n, 1] = x_; log[n, 2] = y_; log[n, 5] = s[5]; log[n, 11] = buf[int(pl['ndel'])]
        if n > 0:
            log[n, 8:11] = log[n-1, 8:11]    # latest truth for oracle references; measured wrappers hide these columns
        F_seen = log[n, 5]
        ycmd = float(policy(OLD.Obs(log, n+1)))
        if not np.isfinite(ycmd):
            ycmd = float(buf[int(pl['ndel'])])
        n0 = n
        n, kk = _tick(s, buf, ycmd, c, a[0], a[1], a[2], a[3], a[4], a[5], a[6], a[7], a[8], sig, noise, kk, log, n, True)
        if n < 0:
            return None
        log[n0, 5] = F_seen
    return log[:n]


def replay(sc, commands, seed=0, sensor=False, platform=None):
    """Open-loop replay of a command sequence; the plant is deterministic given commands and noise."""
    pl = dict(PLATFORM if platform is None else platform)
    T = sc['T']; nt = len(commands)
    log = np.zeros((nt+2, LOGC)); s, buf = _init(sc, pl)
    c = _constants(sc, pl)
    rng = np.random.default_rng(seed)
    noise = rng.standard_normal((int(T*1000)+10, 2)) if sensor else np.zeros((int(T*1000)+10, 2))
    a = _arrays(sc); n = 0; kk = 0
    for i in range(nt):
        F_seen = s[5]
        n0 = n
        n, kk = _tick(s, buf, float(commands[i]), c, a[0], a[1], a[2], a[3], a[4], a[5], a[6], a[7], a[8], .08, noise, kk, log, n, True)
        if n < 0:
            return None
        log[n0, 5] = F_seen
    return log[:n]
