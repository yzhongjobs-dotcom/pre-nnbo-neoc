"""Tables for the large-cohort evaluation (results_v2/cohort_final.json, robustness_final.json) -> results_v2/tables_cohort.md

Primary evaluation: the untouched final cohort (seeds 130000+, 50 scenes per family), not used for tuning, selection or
diagnosis. RMSE is reported as median and mean (the mean exposes rare failures); failures (numerical/position
divergence) and catastrophic events (true force > 50 N) are counted per family; contact retention by mean loss fraction
and the number of scenes whose longest single loss exceeds 0.5 s. Paired bootstrap of mean RMSE difference
(method - Proposed), 95% CI, 4000 resamples, scenes as units.
"""
import json, os
import numpy as np

H = os.path.dirname(os.path.abspath(__file__)); R = os.path.join(H, 'results_v2')
FAM = ['S2', 'T3m', 'T2m-soft', 'T2m-stiff', 'T2f-stiff']
LAB = {'S2': 'S2 static span', 'T3m': 'S3a spine', 'T2m-soft': 'S3b soft push', 'T2m-stiff': 'S3c stiff push',
       'T2f-stiff': 'S3d fast stiff push (stress)'}
MAIN = ['Proposed', 'RossiType', 'WijType', 'DOMPAC', 'RossiDOMPAC', 'YuenType', 'Oracle', 'Fixed:1109', 'Fixed:28083']
ABL = ['Proposed', 'Abl-noProjection', 'Abl-noExcitation', 'Abl-noConservative', 'Abl-noFeedforward', 'Abl-noBound',
       'Abl-noRecovery', 'Abl-KF', 'Abl-polyFF', 'NoNorm:1109', 'NoNorm:28083']


def latest(rows):
    """keep the last row per (cfg, sid) -- the file accumulates reruns of a configuration."""
    d = {}
    for r in rows: d[(r['cfg'], r['sid'])] = r
    return list(d.values())


def boot(d, n=4000, seed=0):
    r = np.random.default_rng(seed); d = np.asarray(d, float)
    b = [d[r.integers(0, len(d), len(d))].mean() for _ in range(n)]
    return d.mean(), np.percentile(b, 2.5), np.percentile(b, 97.5)


def row(rows, cfg, fam):
    R_ = [r for r in rows if r['cfg'] == cfg and r['family'] == fam]
    ok = [r for r in R_ if r['ok']]
    if not R_: return None
    rm = np.array([r['rmse'] for r in ok])
    return dict(n=len(R_), fail=len(R_)-len(ok), med=np.median(rm), mean=rm.mean(),
                cat=sum(r['peak'] > 50 for r in ok), loss=np.mean([r['loss'] for r in ok]),
                long=sum(r['loss_max'] > .5 for r in ok))


def table(rows, cfgs):
    out = []
    for fam in FAM:
        out += ['### '+LAB[fam], '', '| method | fail | RMSE median [N] | RMSE mean [N] | scenes >50 N | mean loss | longest loss >0.5 s |',
                '|---|---:|---:|---:|---:|---:|---:|']
        for c in cfgs:
            v = row(rows, c, fam)
            if v: out.append('| %s | %d/%d | %.3f | %.3f | %d | %.4f | %d |' % (c, v['fail'], v['n'], v['med'], v['mean'], v['cat'], v['loss'], v['long']))
        out.append('')
    return out


def paired(rows, cfgs):
    out = ['| method − Proposed, mean RMSE [N] (95% CI; Proposed better in) | '+' | '.join(LAB[f] for f in FAM)+' |',
           '|---|'+'---|'*len(FAM)]
    P = {(r['family'], r['sid']): r for r in rows if r['cfg'] == 'Proposed' and r['ok']}
    for c in cfgs:
        if c == 'Proposed': continue
        cells = []
        for f in FAM:
            d = [r['rmse']-P[(f, r['sid'])]['rmse'] for r in rows if r['cfg'] == c and r['family'] == f and r['ok'] and (f, r['sid']) in P]
            if not d: cells.append('—'); continue
            m, lo, hi = boot(d)
            cells.append('%+.3f [%+.3f, %+.3f]; %d/%d' % (m, lo, hi, sum(x > 0 for x in d), len(d)))
        out.append('| %s | ' % c+' | '.join(cells)+' |')
    return out


