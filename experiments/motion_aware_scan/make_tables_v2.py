import json, os
import numpy as np
from collections import defaultdict

H = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(H, 'results_v2')
NAMES = {'Proposed': 'Proposed (IMM motion tracker)', 'RossiType': 'Rossi-type', 'WijType': 'Wijayarathne-type proxy (privileged k)',
         'DOMPAC': 'DO-MPAC', 'RossiDOMPAC': 'Rossi est. + DO-MPAC', 'Oracle': 'Reference (true k, true future surface)',
         'Abl-polyFF': 'window-polynomial feed-forward (earlier version)', 'Abl-KF': 'single-model Kalman tracker', 'Abl-IMM': 'two-model IMM tracker (bandwidth switching)',
         'Abl-noProjection': 'w/o drift projection', 'Abl-noConservative': 'w/o conservative stiffness',
         'Abl-noFeedforward': 'w/o motion feed-forward', 'Abl-noExcitation': 'w/o excitation'}
FAM = {'S2': 'S2 static heterogeneous scan', 'T3m': 'S3a spine scan, breathing + moderate pushes',
       'T2m-soft': 'S3b soft tissue, moderate pushes', 'T2m-stiff': 'S3c stiff tissue, moderate pushes',
       'T2f-stiff': 'S3d stress test: stiff tissue, fast pushes'}


def nm(m):
    return 'Fixed A1 at k=%s N/m' % m.split(':')[1] if m.startswith('Fixed:') else NAMES.get(m, m)


def table(summ, fam, methods):
    rows = ['| Method | fail | RMSE [N] | RMSE w/o excitation line [N] | P95 [N] | worst peak [N] | loss fraction | longest loss [s] | osc RMS [N] |',
            '|---|---:|---:|---:|---:|---:|---:|---:|---:|']
    for m in methods:
        v = summ.get('%s|%s' % (fam, m))
        if v is None:
            continue
        rows.append('| %s | %d/%d | %.3f ± %.3f | %.3f | %.2f | %.1f | %.4f | %.2f | %.3f |' % (
            nm(m), v['n_fail'], v['n'], v['rmse'][0], v['rmse'][1], v['rmse_noexc'], v['p95'], v['peak_max'],
            v['loss_frac'], v['loss_max'], v['osc']))
    return '\n'.join(rows)


def paired(pm, methods):
    fams = list(FAM)
    rows = ['| method − Proposed (RMSE, N) | '+' | '.join(fams)+' |', '|---|'+'---:|'*len(fams)]
    for m in methods:
        cells = []
        for f in fams:
            v = pm.get(f, {}).get(m)
            cells.append('—' if not v or not v['n'] else '%+.3f [%+.3f, %+.3f] (n=%d, Proposed better in %d)' % (
                v['mean'], v['ci'][0], v['ci'][1], v['n'], v['wins']))
        rows.append('| %s | ' % nm(m)+' | '.join(cells)+' |')
    return '\n'.join(rows)


def s1(split):
    rows = json.load(open(os.path.join(R, split, 'S1.json')))
    g = defaultdict(list)
    for r in rows:
        if r.get('diverged'):
            continue
        for ph, v in r['phases'].items():
            g[(r['level'], ph, r['exc'])].append(v)
    out = ['| tissue | phase | excitation | static-surface k̂/k | Rossi band-pass k̂/k | projection k̂/k | empirical coverage |',
           '|---|---|---|---|---|---|---:|']
    for (lvl, ph, ex) in sorted(g, key=lambda x: (['soft', 'mid', 'stiff'].index(x[0]), x[1], not x[2])):
        vs = g[(lvl, ph, ex)]
        def med(k):
            a = np.array([v[k] for v in vs if v.get(k) is not None], float)
            return '—' if len(a) == 0 else '%.2f [%.2f, %.2f]' % (np.median(a[:, 1]), np.median(a[:, 0]), np.median(a[:, 2]))
        cov = [v['cover'] for v in vs if v.get('cover') is not None]
        out.append('| %s | %s | %s | %s | %s | %s | %s |' % (lvl, ph, 'on' if ex else 'off', med('static'), med('rossi'),
                                                         med('proj'), '%.2f' % np.mean(cov) if cov else '—'))
    return '\n'.join(out)


def timing(t):
    rows = ['| method | P50 [ms] | P99 [ms] | worst-scene P99 [ms] | calls > 8 ms |', '|---|---:|---:|---:|---:|']
    for m, v in t.items():
        rows.append('| %s | %.3f | %.3f | %.3f | %.4f |' % (nm(m), v['p50'], v['p99'], v['worst_scene_p99'], v['frac_over_8ms']))
    return '\n'.join(rows)


